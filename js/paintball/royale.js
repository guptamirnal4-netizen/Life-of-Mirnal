// Campus Royale: the whole-campus paintball ruleset. Shared by the game server (which runs it) and the browser
// (maps, zone, HUD). Pure functions and data, no DOM.
//
//   Landing    players pick a landing spot on the campus map from the verified drop registry within
//              ROYALE.landing seconds (squads land together at their leader's pick; anyone who doesn't pick is
//              placed far from everyone else).
//   Supplies   a server-random share of the verified supply spots gets items (js/paintball/items.js).
//   Rules      no respawn: a tag is a round elimination for the match (squads: a teammate can clean you off within
//              ROYALE.down seconds); the play zone shrinks in timed phases towards a random final spot; paint builds
//              up outside it; the last player or squad standing wins.
import { inPoly } from './geometry.js';
import { rollLoot } from './items.js';

export const ROYALE = {
  landing: 20, // s to pick a landing spot
  start: { blaster: 'standard', hopper: 10 }, // everyone lands with a weak start: a Standard blaster, 10 paintballs
  lootShare: 0.7, // share of supply spots that get items each match
  pickRange: 2.4, // m (horizontal) to pick something up
  pickRise: 1.8, // m up or down
  down: 20, // s a fully painted squad member waits for a teammate to clean them off
  revive: 4, // s of cleaning to get them back
  reviveRange: 2.5,
  revivePaint: 60, // paint left on a cleaned-off player
  downSpeed: 0.3, // crawl
  hardCap: 15 * 60, // s: a match never runs longer
  smokeMax: 6, // smoke clouds alive at once
};

// Zone phases: wait (s, the circle holds), shrink (s, to radius r), dps (paint per second outside, from this
// phase on). ~10 minutes from the first circle to nothing.
export const ZONE_PHASES = [
  { wait: 90, shrink: 60, r: 600, dps: 2 },
  { wait: 60, shrink: 50, r: 350, dps: 3 },
  { wait: 50, shrink: 40, r: 200, dps: 5 },
  { wait: 40, shrink: 35, r: 110, dps: 8 },
  { wait: 30, shrink: 30, r: 50, dps: 12 },
  { wait: 25, shrink: 25, r: 15, dps: 18 },
  { wait: 20, shrink: 30, r: 0, dps: 25 },
];
export const zoneLength = (phases = ZONE_PHASES, scale = 1) => phases.reduce((s, p) => s + (p.wait + p.shrink) * scale, 0);

// The circles for one match: circle 0 covers the whole campus; each next one lies inside the previous one and
// contains the final spot; the last is the final spot itself (radius 0).
export function planZone(rand, { centre, startR, final }, phases = ZONE_PHASES) {
  const circles = [{ x: centre.x, z: centre.z, r: startR }];
  for (let i = 0; i < phases.length; i++) {
    const prev = circles[i]; const r = phases[i].r;
    if (r <= 0) { circles.push({ x: final.x, z: final.z, r: 0 }); continue; }
    // a random point within r * 0.8 of the final spot, pulled inside the previous circle
    const a = rand() * Math.PI * 2; const d = Math.sqrt(rand()) * r * 0.8;
    let x = final.x + Math.cos(a) * d; let z = final.z + Math.sin(a) * d;
    const room = prev.r - r;
    if (Math.hypot(x - prev.x, z - prev.z) > room) {
      // straight towards the final spot as far as the previous circle allows (the final spot stays inside)
      const L = Math.hypot(final.x - prev.x, final.z - prev.z); const t = L > room ? room / L : 1;
      x = prev.x + (final.x - prev.x) * t; z = prev.z + (final.z - prev.z) * t;
    }
    circles.push({ x, z, r });
  }
  return circles;
}

// The zone at t seconds into play: { x, z, r, next: { x, z, r }, phase (1-based, 0 before the first), shrinking,
// ends (t when this stage ends), dps, done }.
export function zoneAt(circles, t, phases = ZONE_PHASES, scale = 1) {
  let t0 = 0;
  for (let i = 0; i < phases.length; i++) {
    const a = circles[i]; const b = circles[i + 1]; const ph = phases[i];
    const w = ph.wait * scale; const s = ph.shrink * scale;
    const dps = i === 0 ? 0 : phases[i - 1].dps;
    if (t < t0 + w) return { x: a.x, z: a.z, r: a.r, next: b, phase: i + 1, shrinking: false, ends: t0 + w, dps: i === 0 ? 1 : dps, done: false };
    if (t < t0 + w + s) {
      const k = (t - t0 - w) / s;
      return { x: a.x + (b.x - a.x) * k, z: a.z + (b.z - a.z) * k, r: a.r + (b.r - a.r) * k, next: b, phase: i + 1, shrinking: true, ends: t0 + w + s, dps: ph.dps, done: false };
    }
    t0 += w + s;
  }
  const f = circles[circles.length - 1];
  return { x: f.x, z: f.z, r: 0, next: f, phase: phases.length, shrinking: false, ends: t0, dps: phases[phases.length - 1].dps, done: true };
}
export const outside = (z, x, zz) => Math.hypot(x - z.x, zz - z.z) > z.r;

// ---------- spot validation (the registries are generated by dev/build-royale-spots.mjs and checked again by
// the tests) ----------
export const SPOT_RULES = {
  drop: { clear: 1.5, margin: 3 },
  slot: { clear: 0.8, margin: 3 },
  supply: { clear: 0.6, margin: 3 },
  final: { clear: 3, margin: 60 },
};
export function boundaryDist(B, x, z) {
  let d = Infinity;
  for (let i = 0; i < B.length; i++) {
    const a = B[i]; const b = B[(i + 1) % B.length]; const vx = b[0] - a[0]; const vz = b[1] - a[1];
    const t = Math.max(0, Math.min(1, ((x - a[0]) * vx + (z - a[1]) * vz) / (vx * vx + vz * vz)));
    d = Math.min(d, Math.hypot(x - a[0] - vx * t, z - a[1] - vz * t));
  }
  return d;
}
// geo: CampusGeo. A spot is valid if it is inside the boundary (with margin), not in water, on the ground or a
// walkable floor, and nothing solid is within `clear` metres of a body standing there.
export function validateSpot(geo, x, z, y, { clear = 1, margin = 3 } = {}) {
  if (!inPoly(x, z, geo.boundary)) return { ok: false, why: 'outside the boundary' };
  if (boundaryDist(geo.boundary, x, z) < margin) return { ok: false, why: 'too close to the boundary' };
  if (geo.inWater(x, z)) return { ok: false, why: 'in water' };
  const f = geo.floorAt(x, z, y + 0.05);
  if (Math.abs(f - y) > 0.03) return { ok: false, why: `not on a floor (floor ${f.toFixed(2)}, spot ${y})` };
  if (geo.blockedAt(x, z, y, clear)) return { ok: false, why: `something solid within ${clear} m` };
  return { ok: true };
}

// ---------- registries ----------
// spots: the parsed royale-spots.json. Expands the compact arrays.
export function readSpots(spots) {
  const drops = spots.drops.map(([x, z, y, n, indoor, slots], i) => ({ id: i, x, z, y, name: spots.names[n], indoor: !!indoor, slots: slots.map(([sx, sz]) => ({ x: sx, z: sz, y })) }));
  const supplies = spots.supplies.map(([x, z, y, n, indoor], i) => ({ id: i, x, z, y, name: spots.names[n], indoor: !!indoor }));
  return { drops, supplies, finals: spots.finals };
}

// The nearest drop to (x, z), optionally skipping some ids.
export function nearestDrop(drops, x, z, skip = null) {
  let best = null; let bd = Infinity;
  for (const d of drops) { if (skip?.has(d.id)) continue; const e = (d.x - x) ** 2 + (d.z - z) ** 2; if (e < bd) { bd = e; best = d; } }
  return best;
}

// Landing for every group. groups: [{ key, members: [id], choice: dropId | null }] (a free-for-all player is a
// group of one). Picked drops are honoured (a drop already taken moves you to the nearest free one); groups that
// did not pick are placed as far as possible from everyone already placed. Members land on the drop and its slots.
// Returns Map memberId → { x, z, y, drop }.
export function assignLandings(drops, groups, rand) {
  const out = new Map(); const used = new Set(); const placed = [];
  const land = (g, d) => {
    used.add(d.id); placed.push(d);
    const spots = [d, ...d.slots];
    g.members.forEach((id, i) => {
      let s = spots[i];
      if (!s) { // more members than slots: borrow the next nearest drops
        const extra = nearestDrop(drops, d.x, d.z, used); used.add(extra.id); s = extra;
      }
      out.set(id, { x: s.x, z: s.z, y: s.y, drop: d.id });
    });
  };
  const chose = groups.filter((g) => g.choice !== null && g.choice !== undefined && drops[g.choice]);
  const rest = groups.filter((g) => !chose.includes(g));
  for (const g of chose) {
    let d = drops[g.choice];
    if (used.has(d.id)) d = nearestDrop(drops, d.x, d.z, used);
    land(g, d);
  }
  // farthest-point placement for the rest (outdoor drops, sampled for speed), a little randomness on ties
  const pool = drops.filter((d) => !d.indoor);
  for (const g of rest) {
    let best = null; let bd = -1;
    const start = Math.floor(rand() * pool.length);
    for (let k = 0; k < pool.length; k++) {
      const d = pool[(start + k) % pool.length];
      if (used.has(d.id) || d.slots.length + 1 < Math.min(g.members.length, 6)) continue;
      const near = placed.length ? Math.min(...placed.map((q) => Math.hypot(q.x - d.x, q.z - d.z))) : rand() * 1000;
      if (near > bd) { bd = near; best = d; }
    }
    land(g, best || drops.find((d) => !used.has(d.id)));
  }
  return out;
}

// Items for one match: a random share of the supply spots, each with rollLoot's items.
// Returns [{ item, n, x, y, z, spot }].
export function spawnLoot(supplies, rand, share = ROYALE.lootShare) {
  const out = [];
  for (const s of supplies) {
    if (rand() >= share) continue;
    for (const [item, n] of rollLoot(rand)) out.push({ item, n, x: s.x, y: s.y, z: s.z, spot: s.id });
  }
  return out;
}

// A random final zone centre from the registry.
export function pickFinal(spots, rand) {
  const i = spots.finals[Math.floor(rand() * spots.finals.length)];
  return spots.drops[i];
}
